import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const config = JSON.parse(await readFile(resolve(root, 'src/config.json'), 'utf8'))
const outputPath = resolve(root, 'src/styles/generated-accent.css')

function hexToRgb(hex) {
  const normalized = hex.replace('#', '').trim()
  const full =
    normalized.length === 3 ? [...normalized].map((value) => value + value).join('') : normalized
  const value = Number.parseInt(full, 16)
  return [(value >> 16) & 255, (value >> 8) & 255, value & 255]
}

function rgbToString(rgb) {
  return rgb.map((value) => Math.round(value)).join(' ')
}

function mixRgb(base, accent, weight) {
  return base.map((value, index) => value + (accent[index] - value) * weight)
}

const colors = config.color
const accents = colors.accent.filter(
  (color, index, palette) =>
    palette.findIndex(
      (candidate) => candidate.light === color.light && candidate.dark === color.dark,
    ) === index,
)
const defaultLightAccent = hexToRgb(accents[0].light)
const defaultDarkAccent = hexToRgb(accents[0].dark)

const blocks = [
  '/* Generated by scripts/generate-accent-css.mjs. */',
  'html {',
  `  --color-accent: ${rgbToString(defaultLightAccent)};`,
  `  --color-bg-root: ${rgbToString(mixRgb([250, 250, 250], defaultLightAccent, 0.05))};`,
  `  --color-bg-primary: ${rgbToString(hexToRgb(colors.bg.primary.light))};`,
  `  --color-bg-secondary: ${rgbToString(hexToRgb(colors.bg.secondary.light))};`,
  `  --color-text-primary: ${rgbToString(hexToRgb(colors.text.primary.light))};`,
  `  --color-text-secondary: ${rgbToString(hexToRgb(colors.text.secondary.light))};`,
  `  --color-border-primary: ${rgbToString(hexToRgb(colors.border.primary.light))};`,
  '}',
  '',
  "[data-theme='dark'] {",
  `  --color-accent: ${rgbToString(defaultDarkAccent)};`,
  `  --color-bg-root: ${rgbToString(mixRgb([0, 2, 18], defaultDarkAccent, 0.12))};`,
  `  --color-bg-primary: ${rgbToString(hexToRgb(colors.bg.primary.dark))};`,
  `  --color-bg-secondary: ${rgbToString(hexToRgb(colors.bg.secondary.dark))};`,
  `  --color-text-primary: ${rgbToString(hexToRgb(colors.text.primary.dark))};`,
  `  --color-text-secondary: ${rgbToString(hexToRgb(colors.text.secondary.dark))};`,
  `  --color-border-primary: ${rgbToString(hexToRgb(colors.border.primary.dark))};`,
  '}',
  '',
]

accents.forEach((accent, index) => {
  const light = hexToRgb(accent.light)
  const dark = hexToRgb(accent.dark)
  blocks.push(
    `html[data-accent='${index}'] {`,
    `  --color-accent: ${rgbToString(light)};`,
    `  --color-bg-root: ${rgbToString(mixRgb([250, 250, 250], light, 0.05))};`,
    '}',
    '',
    `html[data-accent='${index}'][data-theme='dark'] {`,
    `  --color-accent: ${rgbToString(dark)};`,
    `  --color-bg-root: ${rgbToString(mixRgb([0, 2, 18], dark, 0.12))};`,
    '}',
    '',
  )
})

await writeFile(outputPath, `${blocks.join('\n').trim()}\n`)
console.log(`Generated ${accents.length} accent themes in src/styles/generated-accent.css`)
