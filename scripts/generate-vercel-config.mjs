import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { relative, resolve, sep } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const postsRoot = resolve(root, 'src/content/posts')
const outputPath = resolve(root, 'vercel.json')
const openRestyOutputPath = resolve(root, 'deploy/openresty/agentic.conf')
const checkOnly = process.argv.includes('--check')

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = await Promise.all(
    entries
      .filter((entry) => entry.name !== '.obsidian')
      .map((entry) => {
        const path = resolve(directory, entry.name)
        return entry.isDirectory() ? walk(path) : path
      }),
  )
  return files.flat().filter((path) => path.endsWith('.md'))
}

function parseFrontmatter(source, file) {
  const match = source.replace(/^\uFEFF/, '').match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (!match) throw new Error(`Missing frontmatter: ${relative(root, file)}`)

  const result = new Map()
  for (const line of match[1].split(/\r?\n/)) {
    const scalar = line.match(/^([A-Za-z][\w-]*):\s*(.*?)\s*$/)
    if (!scalar || result.has(scalar[1])) continue
    let value = scalar[2]
    if (
      value.length >= 2 &&
      ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'")))
    ) {
      value = value.slice(1, -1)
    }
    result.set(scalar[1], value)
  }
  return result
}

function slugify(value) {
  return value.replace(/\./g, '').replace(/\s/g, '-').toLowerCase()
}

function buildRedirects(posts) {
  const redirects = new Map()

  const add = (source, destination, file) => {
    const current = redirects.get(source)
    if (current && current.destination !== destination) {
      throw new Error(
        `Conflicting legacy route ${source}: ${current.destination} (${current.file}) and ${destination} (${file})`,
      )
    }
    redirects.set(source, { destination, file })
  }

  for (const post of posts) {
    const path = relative(postsRoot, post.file).split(sep).join('/').replace(/\.md$/i, '')
    const segments = path.split('/')
    const isColumn = segments.length >= 3 && ['专栏', 'column'].includes(segments[0])
    const slug = String(post.frontmatter.get('slug') || path)
    const title = post.frontmatter.get('title')
    if (!title) throw new Error(`Missing title: ${relative(root, post.file)}`)

    const destination = isColumn
      ? `/columns/${slugify(segments[1])}/${segments.at(-1)}`
      : `/posts/${slug}`

    if (isColumn) add(`/posts/${slug}`, destination, relative(root, post.file))
    if (title !== slug) add(`/posts/${title}`, destination, relative(root, post.file))
  }

  return [...redirects.entries()]
    .sort(([a], [b]) => a.localeCompare(b, 'zh-CN'))
    .map(([source, { destination }]) => ({ source, destination, permanent: true }))
}

function nginxQuote(value) {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`
}

function buildOpenRestyConfig(redirects) {
  const lines = [
    '# Generated by scripts/generate-vercel-config.mjs.',
    '# Paste or include this file inside the site server { } block.',
    '# Keep these rules before any generic location / block.',
    '',
    '# Legacy article paths: return real HTTP 308 responses.',
  ]

  for (const { source, destination } of redirects) {
    for (const candidate of [source, `${source}/`]) {
      lines.push(`if ($uri = ${nginxQuote(candidate)}) { return 308 ${nginxQuote(destination)}; }`)
    }
  }

  lines.push(
    '',
    '# Homepage Markdown negotiation.',
    'location = / {',
    '  add_header Vary "Accept, Accept-Encoding" always;',
    '  if ($http_accept ~* "text/markdown") { rewrite ^ /llms.txt last; }',
    '  try_files /index.html =404;',
    '}',
    '',
    'location = /llms.txt {',
    '  default_type text/markdown;',
    '  charset utf-8;',
    '  charset_types text/markdown;',
    '  add_header Vary "Accept, Accept-Encoding" always;',
    '  try_files $uri =404;',
    '}',
    '',
    '# Article HTML/Markdown negotiation. The negative lookahead prevents .md.md loops.',
    'location ^~ /posts/ {',
    '  default_type text/markdown;',
    '  charset utf-8;',
    '  charset_types text/markdown;',
    '  add_header Vary "Accept, Accept-Encoding" always;',
    '  if ($http_accept ~* "text/markdown") {',
    '    rewrite ^/posts/(?!.*\\.md$)([^/]+)/?$ /posts/$1.md last;',
    '  }',
    '  try_files $uri $uri/ $uri/index.html =404;',
    '}',
    '',
    'location ^~ /columns/ {',
    '  default_type text/markdown;',
    '  charset utf-8;',
    '  charset_types text/markdown;',
    '  add_header Vary "Accept, Accept-Encoding" always;',
    '  if ($http_accept ~* "text/markdown") {',
    '    rewrite ^/columns/([^/]+)/(?!.*\\.md$)([^/]+)/?$ /columns/$1/$2.md last;',
    '  }',
    '  try_files $uri $uri/ $uri/index.html =404;',
    '}',
  )

  return `${lines.join('\n')}\n`
}

const files = await walk(postsRoot)
const posts = await Promise.all(
  files.map(async (file) => ({
    file,
    frontmatter: parseFrontmatter(await readFile(file, 'utf8'), file),
  })),
)
const publicPosts = posts.filter(({ frontmatter }) => {
  return frontmatter.get('draft') !== 'true' && frontmatter.get('unlisted') !== 'true'
})

const config = {
  $schema: 'https://openapi.vercel.sh/vercel.json',
  redirects: buildRedirects(publicPosts),
  rewrites: [
    {
      source: '/',
      has: [{ type: 'header', key: 'accept', value: '.*text/markdown.*' }],
      destination: '/llms.txt',
    },
    {
      source: '/posts/:slug',
      has: [{ type: 'header', key: 'accept', value: '.*text/markdown.*' }],
      destination: '/posts/:slug.md',
    },
    {
      source: '/columns/:column/:post',
      has: [{ type: 'header', key: 'accept', value: '.*text/markdown.*' }],
      destination: '/columns/:column/:post.md',
    },
  ],
  headers: [
    {
      source: '/',
      headers: [{ key: 'Vary', value: 'Accept, Accept-Encoding' }],
    },
    {
      source: '/posts/:path*',
      headers: [{ key: 'Vary', value: 'Accept, Accept-Encoding' }],
    },
    {
      source: '/columns/:path*',
      headers: [{ key: 'Vary', value: 'Accept, Accept-Encoding' }],
    },
  ],
}

const serialized = `${JSON.stringify(config, null, 2)}\n`
const openRestySerialized = buildOpenRestyConfig(config.redirects)
if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  const currentOpenResty = await readFile(openRestyOutputPath, 'utf8').catch(() => '')
  if (current !== serialized || currentOpenResty !== openRestySerialized) {
    throw new Error('Agent routing config is stale. Run `pnpm generate:vercel`.')
  }
} else {
  await mkdir(resolve(root, 'deploy/openresty'), { recursive: true })
  await writeFile(outputPath, serialized)
  await writeFile(openRestyOutputPath, openRestySerialized)
  console.log(`Generated ${config.redirects.length} HTTP redirects for Vercel and OpenResty`)
}
